// Generates the SDK's core from the API's OpenAPI document:
//
// - types_gen.go, the wire types, written by oapi-codegen from a copy of the
//   document that this script first rewrites (the pre-load step, below);
// - operations_gen.go, the operation table: what the SDK needs to know about
//   each operation it calls, beyond its types.
//
// Usage, from the package directory:
//   node scripts/generate.mjs                 writes both files
//   node scripts/generate.mjs --check         exits 1 when either file is stale
//   node scripts/generate.mjs --spec <file>   reads another copy of the document
//
// oapi-codegen runs through `go run` at a pinned version, so it never enters
// the module's requirements. Both files are committed and reviewed as a diff
// at every regeneration. The document exists only in the monorepo, so this
// script runs there.

import { spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

const packageDir = join(dirname(fileURLToPath(import.meta.url)), "..");

/** The API's OpenAPI document, beside this package in the monorepo. */
export const SPEC_PATH = join(packageDir, "..", "openapi", "openapi.yaml");

/** The generator, at the version every regeneration uses. */
export const OAPI_CODEGEN =
  "github.com/oapi-codegen/oapi-codegen/v2/cmd/oapi-codegen@v2.8.0";

/** The files this script writes, relative to the package directory. */
export const OUTPUTS = {
  types: "types_gen.go",
  operations: "operations_gen.go",
};

/** The oapi-codegen configuration and the Overlay, in the package directory. */
const CONFIG = "oapi-codegen.yaml";
const OVERLAY = "overlay.yaml";

/** The scalar schemas, inlined wherever they are referenced. */
export const SCALARS = [
  "Uuid",
  "UuidInput",
  "Instant",
  "InstantInput",
  "Date",
  "DateInput",
  "Month",
  "Currency",
  "MinorUnits",
  "Money",
  "Ratio",
];

/** The access policies of the operations the SDK calls. */
const SDK_POLICIES = new Set(["KeyOnly", "KeyOrSession", "Public"]);

/** The schema the SDK's own Client type would collide with, and its Go name. */
const RENAMED = { Client: "ClientRecord" };

const SCHEMAS = "#/components/schemas/";

/** The CSV delimiters, which the SDK declares as ImportDelimiter constants. */
const DELIMITERS = [",", ";", "\t"];

/**
 * The extensions each Overlay entry sets beside its `x-go-type`: a value
 * rather than a pointer, tagged `omitzero` and not `omitempty`, which has
 * no effect on a struct.
 */
const NULLABLE_TAGS = {
  "x-go-type-skip-optional-pointer": true,
  "x-omitzero": true,
  "x-omitempty": false,
};

/** The first lines oapi-codegen writes, replaced by this script's header. */
const OAPI_HEADER =
  /^\/\/ Package allisall provides primitives to interact with the openapi HTTP API\.\n\/\/\n(\/\/ Code generated by github\.com\/oapi-codegen\/oapi-codegen\/v2 version v2\.8\.0 DO NOT EDIT\.)\npackage allisall\n/;

const NOTE = `// Generated from the API's OpenAPI document by scripts/generate.mjs.
// Never edit this file by hand: change the document or the script, and
// regenerate.`;

function isObject(value) {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

/** Resolves a local `$ref`, such as `#/components/schemas/Money`. */
export function resolveRef(spec, ref) {
  if (!ref.startsWith("#/")) throw new Error(`${ref} is not a local reference`);
  let node = spec;
  for (const raw of ref.slice(2).split("/")) {
    const key = raw.replaceAll("~1", "/").replaceAll("~0", "~");
    if (!isObject(node) || !(key in node)) {
      throw new Error(`${ref} does not resolve`);
    }
    node = node[key];
  }
  return node;
}

function deref(spec, value) {
  return isObject(value) && typeof value.$ref === "string"
    ? resolveRef(spec, value.$ref)
    : value;
}

/** Calls fn on every object in the tree, parents before children. */
function visitObjects(node, fn) {
  if (Array.isArray(node)) {
    for (const item of node) visitObjects(item, fn);
    return;
  }
  if (!isObject(node)) return;
  fn(node);
  for (const value of Object.values(node)) visitObjects(value, fn);
}

/** Refuses a `$ref` that is not local or does not resolve. */
function checkRefs(spec) {
  visitObjects(spec, (node) => {
    if (typeof node.$ref === "string") resolveRef(spec, node.$ref);
  });
}

/** Whether a schema is a closed set of strings: an `enum`, or a `oneOf` of `const`s. */
function isClosedSet(spec, schema) {
  const resolved = deref(spec, schema);
  if (!isObject(resolved)) return false;
  if (Array.isArray(resolved.enum)) return true;
  return (
    Array.isArray(resolved.oneOf) &&
    resolved.oneOf.length > 0 &&
    resolved.oneOf.every((b) => isObject(b) && b.const !== undefined)
  );
}

/** Whether a schema is a bare string: any string, with no `enum`, `const` or `$ref`. */
function isBareString(schema) {
  return (
    isObject(schema) &&
    schema.type === "string" &&
    schema.enum === undefined &&
    schema.const === undefined &&
    schema.$ref === undefined
  );
}

/** Whether a schema admits `null`: `type: "null"`, a type list holding it, or a union with such a branch. */
function admitsNull(spec, schema) {
  const s = deref(spec, schema);
  if (!isObject(s)) return false;
  if (s.type === "null") return true;
  if (Array.isArray(s.type) && s.type.includes("null")) return true;
  for (const key of ["anyOf", "oneOf"]) {
    if ((s[key] ?? []).some((b) => admitsNull(spec, b))) return true;
  }
  return false;
}

const BODY_KINDS = [
  ["multipart/form-data", "multipart"],
  ["application/merge-patch+json", "merge-patch"],
  ["application/json", "json"],
];

/**
 * The operations the SDK calls: each one with a `2xx` response, other than a
 * `HEAD`, whose access policy an API key or no credential meets. Every
 * operation with a `2xx` response is checked, so a malformed one is refused
 * even when the SDK does not call it.
 */
export function sdkOperations(spec) {
  const out = [];
  for (const [path, item] of Object.entries(spec.paths ?? {})) {
    if (!isObject(item)) continue;
    for (const [method, operation] of Object.entries(item)) {
      if (!isObject(operation) || typeof operation.operationId !== "string") {
        continue;
      }
      if (method === "head") continue;
      const id = operation.operationId;
      const success = Object.keys(operation.responses ?? {}).filter((s) =>
        /^2\d\d$/.test(s),
      );
      if (success.length === 0) continue;
      if (success.length > 1) {
        throw new Error(`${id} has more than one 2xx response`);
      }
      const access = operation["x-access"];
      if (!isObject(access) || typeof access.policy !== "string") {
        throw new Error(`${id} has no x-access policy`);
      }
      if (typeof operation["x-idempotent"] !== "boolean") {
        throw new Error(`${id} has no boolean x-idempotent`);
      }
      if (!SDK_POLICIES.has(access.policy)) continue;

      const requestBody = deref(spec, operation.requestBody);
      const content = isObject(requestBody) ? (requestBody.content ?? {}) : {};
      const types = Object.keys(content);
      let body = "none";
      let bodySchema = null;
      if (types.length > 0) {
        const kind = BODY_KINDS.find(([type]) => types.includes(type));
        if (kind === undefined) {
          throw new Error(`${id} takes a request body the SDK does not send`);
        }
        body = kind[1];
        bodySchema = content[kind[0]].schema;
      }
      out.push({
        id,
        method: method.toUpperCase(),
        path,
        access: access.policy,
        scope: typeof access.scope === "string" ? access.scope : "",
        idempotent: operation["x-idempotent"],
        list:
          typeof operation["x-list"] === "string" ? operation["x-list"] : "",
        body,
        bodySchema,
        status: Number(success[0]),
        operation,
        item,
      });
    }
  }
  return out.sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
}

/**
 * The component schemas the SDK's operations reach: from their parameters,
 * their request bodies and their success responses, through every `$ref`.
 * A schema reached only from an error response is not among them.
 */
export function reachedSchemas(spec, operations) {
  const reached = new Set();
  const visit = (node) => {
    visitObjects(node, (obj) => {
      if (typeof obj.$ref !== "string") return;
      if (obj.$ref.startsWith(SCHEMAS)) {
        const name = obj.$ref.slice(SCHEMAS.length);
        if (reached.has(name)) return;
        reached.add(name);
        visit(resolveRef(spec, obj.$ref));
      } else {
        visit(resolveRef(spec, obj.$ref));
      }
    });
  };
  for (const op of operations) {
    visit(op.item.parameters);
    visit(op.operation.parameters);
    visit(op.operation.requestBody);
    visit(op.operation.responses[String(op.status)]);
  }
  return reached;
}

/**
 * The nullable members of every merge-patch body, as Overlay targets such as
 * `$.components.schemas.ClientPatch.properties.notes`. A patch body must be a
 * component schema, so that each member can be named by a path.
 */
export function nullablePatchMembers(spec, operations) {
  const out = new Set();
  for (const op of operations) {
    if (op.body !== "merge-patch") continue;
    const ref = op.bodySchema?.$ref;
    if (typeof ref !== "string" || !ref.startsWith(SCHEMAS)) {
      throw new Error(
        `${op.id} takes a merge patch that is not a component schema`,
      );
    }
    const name = ref.slice(SCHEMAS.length);
    const schema = resolveRef(spec, ref);
    for (const [member, value] of Object.entries(schema.properties ?? {})) {
      if (admitsNull(spec, value)) {
        out.add(`$.components.schemas.${name}.properties.${member}`);
      }
    }
  }
  return out;
}

/** The Go type of a nullable member's other branch, for `Nullable[T]`. */
function nonNullGoType(spec, member) {
  const s = deref(spec, member);
  const branches = (s.anyOf ?? s.oneOf ?? [s]).filter(
    (b) => !(isObject(b) && b.type === "null"),
  );
  if (branches.length !== 1) return null;
  const branch = branches[0];
  if (branch.$ref === `${SCHEMAS}Money`) return "Decimal";
  const t = deref(spec, branch);
  const type = Array.isArray(t.type)
    ? t.type.filter((x) => x !== "null")
    : [t.type];
  if (type.length !== 1) return null;
  if (type[0] === "string" && t.format !== "date-time") return "string";
  if (type[0] === "string") return "time.Time";
  return (
    { integer: "int", boolean: "bool", number: "float64" }[type[0]] ?? null
  );
}

/**
 * Checks the Overlay against the document: it names exactly the nullable
 * members of the merge-patch bodies, each as a `Nullable` of its own type.
 */
export function checkOverlay(spec, operations, overlay) {
  const expected = nullablePatchMembers(spec, operations);
  const named = new Map();
  for (const action of overlay.actions ?? []) {
    const { "x-go-type": goType, ...tags } = action.update ?? {};
    // Left out when absent through omitzero, with no inert omitempty.
    if (JSON.stringify(tags) !== JSON.stringify(NULLABLE_TAGS)) {
      throw new Error(
        `${OVERLAY} gives ${action.target} ${JSON.stringify(tags)}, not ${JSON.stringify(NULLABLE_TAGS)}`,
      );
    }
    named.set(action.target, goType);
  }
  for (const target of expected) {
    if (!named.has(target)) {
      throw new Error(
        `${target} is a nullable member of a merge patch, and ${OVERLAY} does not name it`,
      );
    }
  }
  for (const [target, goType] of named) {
    if (!expected.has(target)) {
      throw new Error(
        `${OVERLAY} names ${target}, which is not a nullable member of a merge patch`,
      );
    }
    const [, schema, member] =
      /^\$\.components\.schemas\.(\w+)\.properties\.(\w+)$/.exec(target);
    const want = nonNullGoType(
      spec,
      spec.components.schemas[schema].properties[member],
    );
    if (want === null || goType !== `Nullable[${want}]`) {
      throw new Error(
        `${OVERLAY} gives ${target} the type ${goType}, but its value is ${want ?? "not a single type"}`,
      );
    }
  }
}

/** Replaces the `$ref` of a scalar with the scalar's shape, keeping the member's own keywords. */
function inlineScalar(spec, node) {
  const name = node.$ref.slice(SCHEMAS.length);
  const scalar = structuredClone(spec.components.schemas[name]);
  // The scalar's prose describes the scalar, not the member; the member's
  // own description, if any, is what its field's comment should say.
  delete scalar.description;
  delete scalar.examples;
  const { $ref, ...own } = node;
  const inlined = { ...scalar, ...own };
  if (name === "Money") inlined["x-go-type"] = "Decimal";
  return inlined;
}

/** Rewrites a tree in place, replacing each object fn returns a replacement for. */
function rewriteTree(node, fn) {
  if (Array.isArray(node)) {
    for (let i = 0; i < node.length; i++) node[i] = rewriteTree(node[i], fn);
    return node;
  }
  if (!isObject(node)) return node;
  let current = node;
  for (;;) {
    const next = fn(current);
    if (next === undefined) break;
    current = next;
  }
  for (const key of Object.keys(current)) {
    current[key] = rewriteTree(current[key], fn);
  }
  return current;
}

/**
 * The pre-load step: the document as oapi-codegen should read it. It returns
 * a new document and leaves `spec` unchanged.
 */
export function preload(spec, operations) {
  const out = structuredClone(spec);
  const schemas = out.components.schemas;
  const reached = reachedSchemas(spec, operations);

  // The query of each operation, inline, and nothing else of it. Only an
  // operation with a query is kept: the generator writes one Params type
  // for each, holding the query alone. The path's own parameters stay,
  // because the generator refuses a path template that declares none; it
  // writes no type for them.
  const paths = {};
  for (const op of operations) {
    const params = [
      ...(op.item.parameters ?? []),
      ...(op.operation.parameters ?? []),
    ]
      .map((p) => structuredClone(deref(spec, p)))
      .filter((p) => p.in === "query" || p.in === "path");
    if (!params.some((p) => p.in === "query")) continue;
    paths[op.path] ??= {};
    paths[op.path][op.method.toLowerCase()] = {
      operationId: op.id,
      parameters: params,
      responses: { default: { description: "Unused by the generator." } },
    };
  }
  out.paths = paths;
  for (const key of ["parameters", "headers", "responses", "requestBodies"]) {
    delete out.components[key];
  }
  delete out.webhooks;

  // Only the schemas the operations reach, and no scalar.
  for (const name of Object.keys(schemas)) {
    if (!reached.has(name)) delete schemas[name];
  }

  rewriteTree(out, (node) => {
    // The generator does not read if, then and else.
    if ("if" in node || "then" in node || "else" in node) {
      const { if: _i, then: _t, else: _e, ...rest } = node;
      return rest;
    }
    // An integer of one value, a `const` or a one-value `enum`: a plain
    // integer. The generator would declare a type and a constant for the
    // one value, which say nothing a caller can choose between.
    if (
      node.type === "integer" &&
      ("const" in node || (Array.isArray(node.enum) && node.enum.length === 1))
    ) {
      const { const: _c, enum: _n, ...rest } = node;
      return rest;
    }
    // An open set: the closed set alone. A Go string type decodes any
    // string, so the type stays open.
    if (Array.isArray(node.anyOf) && node.anyOf.length === 2) {
      const [a, b] = node.anyOf;
      let closed = null;
      if (isClosedSet(spec, a) && isBareString(b)) closed = a;
      else if (isClosedSet(spec, b) && isBareString(a)) closed = b;
      if (closed !== null) {
        const { anyOf: _a, ...rest } = node;
        return { ...rest, ...structuredClone(closed) };
      }
    }
    if (typeof node.$ref === "string") {
      const name = node.$ref.startsWith(SCHEMAS)
        ? node.$ref.slice(SCHEMAS.length)
        : null;
      if (name !== null && SCALARS.includes(name))
        return inlineScalar(spec, node);
      if (name !== null && name in RENAMED) {
        return { ...node, $ref: `${SCHEMAS}${RENAMED[name]}` };
      }
    }
    return undefined;
  });

  for (const name of SCALARS) delete schemas[name];
  for (const [from, to] of Object.entries(RENAMED)) {
    if (!(from in schemas)) continue;
    const { description, ...rest } = schemas[from];
    schemas[to] = {
      ...rest,
      description:
        `${description ?? ""}\n\nIn the API reference, this schema is named ${from}.`.trim(),
    };
    delete schemas[from];
  }

  // The tab in the delimiter's enum cannot be a Go constant name; the SDK
  // declares the delimiters itself.
  const delimiter = schemas.ImportMapping?.properties?.delimiter;
  if (delimiter !== undefined) {
    // Compared as sets: the order the spec lists them in does not matter.
    const listed = delimiter.enum;
    const sameSet =
      Array.isArray(listed) &&
      listed.length === DELIMITERS.length &&
      new Set(listed).size === listed.length &&
      DELIMITERS.every((d) => listed.includes(d));
    if (!sameSet) {
      throw new Error(
        `ImportMapping.delimiter lists ${JSON.stringify(delimiter.enum)}, but the SDK declares constants for ${JSON.stringify(DELIMITERS)}`,
      );
    }
    const { enum: _e, ...rest } = delimiter;
    schemas.ImportMapping.properties.delimiter = { ...rest, type: "string" };
  }

  checkRefs(out);
  visitObjects(out, (node) => {
    if (node.$ref === `${SCHEMAS}Money` || "if" in node) {
      throw new Error(
        "the pre-load step left a shape the generator would misread",
      );
    }
  });
  return out;
}

function goString(s) {
  return JSON.stringify(s);
}

const ACCESS = {
  KeyOnly: "accessKeyOnly",
  KeyOrSession: "accessKeyOrSession",
  Public: "accessPublic",
};
const LIST = { "": "listNone", keyset: "listKeyset", offset: "listOffset" };
const BODY = {
  none: "bodyNone",
  json: "bodyJSON",
  "merge-patch": "bodyMergePatch",
  multipart: "bodyMultipart",
};

/** The operation table, as Go source. */
export function renderOperations(operations) {
  const entries = operations.map((op) => {
    for (const [value, table] of [
      [op.access, ACCESS],
      [op.list, LIST],
      [op.body, BODY],
    ]) {
      if (!(value in table))
        throw new Error(`${op.id}: ${value} is not a kind the table knows`);
    }
    return `\t{
\t\tid:         ${goString(op.id)},
\t\tmethod:     ${goString(op.method)},
\t\tpath:       ${goString(op.path)},
\t\taccess:     ${ACCESS[op.access]},
\t\tscope:      ${goString(op.scope)},
\t\tidempotent: ${op.idempotent},
\t\tlist:       ${LIST[op.list]},
\t\tbody:       ${BODY[op.body]},
\t\tstatus:     ${op.status},
\t},`;
  });
  return `// Code generated by scripts/generate.mjs DO NOT EDIT.
${NOTE}

package allisall

// accessPolicy is who may call an operation.
type accessPolicy int

const (
\t// accessKeyOnly takes an API key holding the operation's scope.
\taccessKeyOnly accessPolicy = iota + 1
\t// accessKeyOrSession takes an API key holding the operation's scope, or a session token.
\taccessKeyOrSession
\t// accessPublic takes no credential.
\taccessPublic
)

// listKind is what a list operation's cursor holds.
type listKind int

const (
\t// listNone is an operation that is not a list.
\tlistNone listKind = iota
\t// listKeyset is a list whose cursor holds the last item's sort key.
\tlistKeyset
\t// listOffset is a list whose cursor holds an offset.
\tlistOffset
)

// bodyKind is the request body an operation takes.
type bodyKind int

const (
\t// bodyNone is an operation that takes no body.
\tbodyNone bodyKind = iota
\t// bodyJSON is an application/json body.
\tbodyJSON
\t// bodyMergePatch is an application/merge-patch+json body.
\tbodyMergePatch
\t// bodyMultipart is a multipart/form-data body.
\tbodyMultipart
)

// operation is what the SDK needs to know about one operation, beyond its
// types.
type operation struct {
\t// id is the operation's operationId.
\tid string
\t// method is the HTTP method.
\tmethod string
\t// path is the path template, such as "/v1/clients/{id}".
\tpath string
\t// access is who may call it.
\taccess accessPolicy
\t// scope is the scope an API key needs, or "" when the policy names none.
\tscope string
\t// idempotent reports whether it takes an Idempotency-Key.
\tidempotent bool
\t// list is its list kind.
\tlist listKind
\t// body is the request body it takes.
\tbody bodyKind
\t// status is the status of its success response.
\tstatus int
}

// operationTable returns one entry per operation the SDK calls, sorted by
// operationId.
func operationTable() []operation {
\treturn []operation{
${entries.join("\n")}
\t}
}
`;
}

function run(cmd, args, options) {
  const result = spawnSync(cmd, args, {
    cwd: packageDir,
    encoding: "utf8",
    maxBuffer: 1 << 26,
    ...options,
  });
  if (result.error) throw result.error;
  if (result.status !== 0) {
    throw new Error(
      `${cmd} ${args.join(" ")} failed:\n${result.stderr}${result.stdout}`,
    );
  }
  return result.stdout;
}

/** Runs oapi-codegen on the rewritten document, and returns types_gen.go. */
function renderTypes(rewritten) {
  const dir = mkdtempSync(join(tmpdir(), "allisall-go-generate-"));
  try {
    const input = join(dir, "openapi.json");
    const output = join(dir, OUTPUTS.types);
    writeFileSync(input, JSON.stringify(rewritten));
    run("go", ["run", OAPI_CODEGEN, "-config", CONFIG, "-o", output, input]);
    const source = readFileSync(output, "utf8");
    const match = OAPI_HEADER.exec(source);
    if (match === null) {
      throw new Error(
        `oapi-codegen's output does not start with the header this script replaces`,
      );
    }
    // The generator's own first line would become the package's
    // documentation; the package documents itself elsewhere.
    return `${match[1]}\n${NOTE}\n\npackage allisall\n${source.slice(match[0].length)}`;
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

/** Formats Go source with gofmt, as the linter expects it. */
function gofmt(source) {
  return run("gofmt", [], { input: source });
}

/**
 * Generates both files from the document's text. Returns each file's content
 * by its path relative to the package directory.
 */
export function generate(specText) {
  const spec = parse(specText);
  checkRefs(spec);
  const operations = sdkOperations(spec);
  checkOverlay(
    spec,
    operations,
    parse(readFileSync(join(packageDir, OVERLAY), "utf8")),
  );
  return {
    [OUTPUTS.types]: gofmt(renderTypes(preload(spec, operations))),
    [OUTPUTS.operations]: gofmt(renderOperations(operations)),
  };
}

function main() {
  const args = process.argv.slice(2);
  const check = args.includes("--check");
  const specAt = args.indexOf("--spec");
  const specPath = specAt >= 0 ? args[specAt + 1] : SPEC_PATH;
  if (specAt >= 0 && specPath === undefined) {
    throw new Error("--spec needs a file");
  }
  const files = generate(readFileSync(specPath, "utf8"));
  if (check) {
    const stale = staleFiles(files, packageDir);
    for (const file of stale) {
      console.error(`${file} is stale; run node scripts/generate.mjs`);
    }
    if (stale.length > 0) process.exit(1);
    return;
  }
  for (const [file, content] of Object.entries(files)) {
    writeFileSync(join(packageDir, file), content);
  }
}

/** The files, of those generated, whose copy in dir differs or is missing. */
export function staleFiles(files, dir) {
  const out = [];
  for (const [file, content] of Object.entries(files)) {
    let current = null;
    try {
      current = readFileSync(join(dir, file), "utf8");
    } catch {
      current = null;
    }
    if (current !== content) out.push(file);
  }
  return out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try {
    main();
  } catch (err) {
    console.error(err instanceof Error ? err.message : err);
    process.exit(1);
  }
}
