// Command get_workspace prints the workspace the API key belongs to.
package main

import (
	"context"
	"errors"
	"fmt"
	"log"

	allisall "github.com/All-is-AI/allisall-go"
)

func main() {
	// Reads the API key from AIA_API_KEY.
	client, err := allisall.NewClient()
	if err != nil {
		log.Fatal(err)
	}

	if err := run(context.Background(), client); err != nil {
		// The API refused the request, for example a key without the read scope.
		var apiErr *allisall.APIError
		if errors.As(err, &apiErr) {
			log.Fatalf("the API refused the request: %d %s (request %s)", apiErr.Status, apiErr.Code, apiErr.RequestID)
		}
		log.Fatal(err)
	}
}

func run(ctx context.Context, client *allisall.Client) error {
	// The API key names the workspace, so the call takes no id.
	workspace, err := client.Workspace.Get(ctx)
	if err != nil {
		return err
	}
	fmt.Printf("%s: figures in %s, created %s\n", workspace.Name, workspace.Currency, workspace.CreatedAt)
	return nil
}
